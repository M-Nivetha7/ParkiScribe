ALL_CLASSES = sorted(list(_RAW_TEMPLATES.keys()))
CLASS_TO_IDX = {cls: idx for idx, cls in enumerate(ALL_CLASSES)}
IDX_TO_CLASS = {idx: cls for idx, cls in enumerate(ALL_CLASSES)}
NUM_CLASSES = len(ALL_CLASSES)


def get_canonical_trajectory(char: str, num_points: int = 64) -> np.ndarray:
    char = char.upper()
    if char not in _RAW_TEMPLATES:
        raise ValueError(f"Character {char} not found in templates. Valid: {ALL_CLASSES}")
    raw_pts = np.array(_RAW_TEMPLATES[char], dtype=np.float32)
    return _interpolate_polyline(raw_pts, num_points=num_points)


def get_all_canonical_trajectories(num_points: int = 64) -> Dict[str, np.ndarray]:
    return {c: get_canonical_trajectory(c, num_points) for c in ALL_CLASSES}
