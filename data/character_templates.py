"""
Canonical character stroke trajectories for air-writing.
Defines canonical 2D/3D stroke anchor points and interpolators for A-Z, 0-9.
"""

from typing import Dict, List, Tuple
import numpy as np


def _interpolate_polyline(points: np.ndarray, num_points: int = 64) -> np.ndarray:
    """Interpolate polyline uniformly along arc-length."""
    if len(points) < 2:
        return np.repeat(points, num_points, axis=0)

    # Compute cumulative arc-length
    diffs = np.diff(points, axis=0)
    seg_lengths = np.linalg.norm(diffs, axis=1)
    total_length = np.sum(seg_lengths)

    if total_length < 1e-6:
        return np.repeat(points[:1], num_points, axis=0)

    cum_dist = np.insert(np.cumsum(seg_lengths), 0, 0.0)
    target_dist = np.linspace(0.0, total_length, num_points)

    resampled = np.zeros((num_points, points.shape[1]), dtype=np.float32)
    for dim in range(points.shape[1]):
        resampled[:, dim] = np.interp(target_dist, cum_dist, points[:, dim])

    return resampled


